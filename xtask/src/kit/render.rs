//! The generated index (`docs/ai/kit/index.md`) and the single-use ratchet text.

use super::{Concept, Kit};
use std::collections::BTreeMap;
use std::fmt::Write;

fn short(path: &str) -> String {
    path.trim_start_matches("crates/").replacen("/src/", "/", 1)
}

fn cell(s: &str) -> String {
    s.replace('|', "/").replace('\n', " ")
}

fn flags(c: &Concept) -> String {
    let mut f = Vec::new();
    if c.used_by.len() < 2 {
        f.push("SINGLE-USE".to_string());
    }
    if !c.local.is_empty() {
        let l: Vec<String> = c.local.iter().map(|(p, _)| short(p)).collect();
        f.push(format!("LOCAL: {}", l.join(", ")));
    }
    f.join("; ")
}

pub fn index(kit: &Kit) -> String {
    let mut out = String::new();
    out.push_str(
        "# Kit index\n\nGenerated by `cargo xtask codegen` from the `//! concept:` headers of the modules of the shared and language crates (see [adding-a-language.md](../architecture/adding-a-language.md)); do not edit.\nOne row per concept (one behavior). `used by`: languages whose grammar, `format.rules` or `lang.yaml` set the data the shared module reads, or whose code names the module. SINGLE-USE: fewer than two users (a shared module that reads no data may stand alone, see single-use.txt). LOCAL: language modules that carry the concept without using the shared mechanism.\n",
    );
    let mut kinds: BTreeMap<&str, Vec<&Concept>> = BTreeMap::new();
    for c in kit.concepts.values() {
        kinds.entry(&c.kind).or_default().push(c);
    }
    for (kind, list) in kinds {
        let _ = write!(
            out,
            "\n## {kind}\n\n| id | module | what | tools | used by | flags |\n|---|---|---|---|---|---|\n"
        );
        for c in list {
            let module = match c.modules.len() {
                0 => String::new(),
                1 => short(&c.modules[0]),
                n => format!("{} +{}", short(&c.modules[0]), n - 1),
            };
            let users: Vec<&str> = c.used_by.iter().map(String::as_str).collect();
            let _ = writeln!(
                out,
                "| {} | {} | {} | {} | {} | {} |",
                c.id,
                module,
                cell(&c.what),
                cell(&c.tools.join("; ")),
                users.join(", "),
                cell(&flags(c)),
            );
        }
    }
    out
}

/// Marks a single-use concept that may be added to the list: its module is in a shared crate and
/// reads no data (`reads:` has only `option:`, `rule:` or `path:` entries), so a second language
/// adopts it by using the module, with nothing to add to its own data.
const SHARED: &str = " (shared)";

fn data_free(c: &Concept) -> bool {
    c.shared
        && c.local.is_empty()
        && c.reads.iter().all(|r| {
            ["option:", "rule:", "path:"]
                .iter()
                .any(|p| r.starts_with(p))
        })
}

pub fn single_use(kit: &Kit) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for c in kit.concepts.values() {
        if c.used_by.len() < 2 {
            let u: Vec<&str> = c.used_by.iter().map(String::as_str).collect();
            out.insert(
                format!("concept {}", c.id),
                format!(
                    "users: {}{}",
                    u.join(", "),
                    if data_free(c) { SHARED } else { "" }
                ),
            );
        }
        for (path, lang) in &c.local {
            out.insert(
                format!("local {} {}", short(path), c.id),
                format!("lang: {lang}"),
            );
        }
    }
    for (item, users) in &kit.data {
        if users.len() < 2 {
            let u: Vec<&str> = users.iter().map(String::as_str).collect();
            out.insert(format!("data {item}"), format!("users: {}", u.join(", ")));
        }
    }
    out
}

const HEADER: &str = "# Single-use list: a ratchet that may only shrink (`cargo xtask codegen --check`).\n# Every data item (grammar line type, format.rules section, row key, grammar tag read by shared code) and every concept\n# with fewer than two users, and every LOCAL entry (a language module that carries a concept without using its shared\n# mechanism). An entry that is no longer true is removed by `cargo xtask codegen`; adding one fails the check:\n# a second language adopts the shared form (docs/ai/architecture/adding-a-language.md). The one exception is a concept\n# of a shared module that reads no data (`reads:` only `option:`, `rule:`, `path:`): codegen adds it, marked `(shared)`.\n";

fn parse(text: &str) -> Vec<&str> {
    text.lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|l| l.split(" # ").next().unwrap_or(l).trim())
        .collect()
}

/// The list text: all current entries (no baseline) or the baseline entries that still hold.
pub fn ratchet_text(kit: &Kit) -> String {
    let mut out = HEADER.to_string();
    for (k, note) in single_use(kit) {
        let _ = writeln!(out, "{k} # {note}");
    }
    out
}

pub fn shrink(kit: &Kit, baseline: &str) -> String {
    let now = single_use(kit);
    let mut out = HEADER.to_string();
    let base = parse(baseline);
    for (k, note) in &now {
        if base.contains(&k.as_str()) || note.ends_with(SHARED) {
            let _ = writeln!(out, "{k} # {note}");
        }
    }
    out
}

pub fn check_ratchet(kit: &Kit, baseline: &str) -> Vec<String> {
    let now = single_use(kit);
    let base: std::collections::BTreeSet<&str> = parse(baseline).into_iter().collect();
    let mut errors = Vec::new();
    for (k, note) in &now {
        if !base.contains(k.as_str()) && !note.ends_with(SHARED) {
            errors.push(format!("two-language rule: new entry `{k}` ({note}); use the shared form in a second language or give the concept a shared module"));
        }
    }
    for k in &base {
        if !now.contains_key(*k) {
            errors.push(format!("`{k}` is no longer single-use or LOCAL: remove it from docs/ai/design/single-use.txt (`cargo xtask codegen` does)"));
        }
    }
    errors
}
