# Writes crates/lang-powershell/src/commands.generated.rs: the cmdlets of the built-in modules of the running
# PowerShell that have a parameter mandatory in every parameter set (`__AllParameterSets`), with their
# positional parameters. The version and modules are in the file's header.
# usage: pwsh -NoProfile -File scripts/gen_powershell_commands.ps1
$ErrorActionPreference = 'Stop'
$modules = 'Microsoft.PowerShell.Management', 'Microsoft.PowerShell.Utility', 'Microsoft.PowerShell.Security', 'Microsoft.PowerShell.Diagnostics', 'Microsoft.PowerShell.Host'
foreach ($m in $modules) { Import-Module $m -ErrorAction SilentlyContinue }
$rows = foreach ($c in (Get-Command -Module $modules -CommandType Cmdlet | Sort-Object Name)) {
    $set = $c.ParameterSets | Where-Object Name -eq '__AllParameterSets'
    if (-not $set) { continue }
    $mandatory = @($set.Parameters | Where-Object IsMandatory | ForEach-Object Name)
    if (-not $mandatory) { continue }
    $positional = @($set.Parameters | Where-Object { $_.Position -ge 0 } | Sort-Object Position | ForEach-Object Name)
    $list = { param($names) ($names | ForEach-Object { '"{0}"' -f $_ }) -join ', ' }
    '    Signature {{ name: "{0}", positional: &[{1}], mandatory: &[{2}], ..Signature::NONE }},' -f $c.Name, (& $list $positional), (& $list $mandatory)
}
$header = "// Generated by scripts/gen_powershell_commands.ps1 from PowerShell $($PSVersionTable.PSVersion) (Get-Command of $($modules -join ', ')):`n" +
    "// the cmdlets with a parameter mandatory in every parameter set, their positional parameters in order, and the mandatory ones.`n" +
    "use core_syntax::signature::Signature;`n`n" +
    "pub static COMMANDS: &[Signature] = &[`n"
$text = $header + ($rows -join "`n") + "`n];`n"
$out = Join-Path $PSScriptRoot '../crates/lang-powershell/src/commands.generated.rs'
[System.IO.File]::WriteAllText($out, $text.Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
"$($rows.Count) cmdlets"
