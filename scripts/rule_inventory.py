#!/usr/bin/env python3
"""Inventory of the built-in rules: how each is implemented and what it costs per language.

  rule_inventory.py            summary table: rule ids per language by implementation kind, rule lines
  rule_inventory.py --list     one row per (rule id, language): kind, default level, upstream ids
  rule_inventory.py --shared   ids that exist in more than one language (the unification candidates)

Kinds: shared (pattern file in core-patterns/shared), pattern (rule file with `rule:`),
family (rule file with `family:`), rust (no rule file). Sources: docs/ai/rules/rules.json (ids,
languages, levels, upstream ids; regenerated by `cargo xtask codegen`) and `crates/*/rules/*.yaml`.
Lines: hand-written Rust of the rule classes of scripts/cost-kinds.txt (as cost.sh --languages)
and the lines of the crate's rule files. Read-only; run from anywhere.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIALECTS = {"less": "css", "scss": "css", "vue": "html", "svelte": "html", "angular": "html"}
RULE_CLASS = re.compile(r"^lang-[^/]+/src/(rules|analysis|semantic|hooks|validate|checks|ng_checks|anchor_rules|value_rules|imports|flow)(\.rs$|/)")


def kinds():
    """{rule id: (kind, crate)} from the rule files."""
    out = {}
    base = os.path.join(ROOT, "crates")
    for crate in sorted(os.listdir(base)):
        for sub, kind_of_plain in (("rules", "pattern"), ("shared", "shared")):
            d = os.path.join(base, crate, sub)
            if not os.path.isdir(d):
                continue
            for name in sorted(os.listdir(d)):
                if not name.endswith(".yaml"):
                    continue
                for doc in open(os.path.join(d, name), encoding="utf-8").read().split("\n---"):
                    m = re.search(r"^id:\s*(\S+)", doc, re.M)
                    if not m:
                        continue
                    k = "family" if re.search(r"^family:", doc, re.M) else kind_of_plain
                    out[m.group(1).strip("'\"")] = (k, crate)
    return out


def lines(path, pred):
    n = 0
    for dp, _, fs in os.walk(path):
        for f in fs:
            p = os.path.join(dp, f)
            if pred(os.path.relpath(p, os.path.join(ROOT, "crates"))):
                n += sum(1 for _ in open(p, encoding="utf-8", errors="replace"))
    return n


def main():
    rules = json.load(open(os.path.join(ROOT, "docs/ai/rules/rules.json"), encoding="utf-8"))["rules"]
    kind = kinds()
    rows = []  # (id, language, kind, default, upstream)
    for r in rules:
        k = kind.get(r["id"], ("rust", ""))[0]
        up = ",".join(f"{u['tool']}:{u['id']}" for u in r.get("upstream", []))
        for lang in r["languages"]:
            rows.append((r["id"], DIALECTS.get(lang, lang), k, r["default_level"], up))
    rows = sorted(set(rows))
    if "--list" in sys.argv:
        for row in rows:
            print("\t".join(row))
        return
    if "--shared" in sys.argv:
        by = {}
        for i, lang, k, dl, up in rows:
            by.setdefault(i, set()).add(lang)
        for i, ls in sorted(by.items()):
            if len(ls) > 1:
                print(i, ",".join(sorted(ls)))
        return
    table = {}
    for i, lang, k, dl, up in rows:
        t = table.setdefault(lang, {"shared": 0, "pattern": 0, "family": 0, "rust": 0, "on": 0})
        t[k] += 1
        t["on"] += dl != "off"
    print(f"{'language':<15}{'ids':>5}{'shared':>7}{'pattern':>8}{'family':>7}{'rust':>5}{'on':>5}{'rust-lines':>11}{'yaml-lines':>11}")
    tot = [0] * 8
    for lang, t in sorted(table.items(), key=lambda x: -sum(x[1][k] for k in ("shared", "pattern", "family", "rust"))):
        crate = os.path.join(ROOT, "crates", "lang-" + lang)
        rl = lines(crate, lambda p: p.endswith(".rs") and RULE_CLASS.search(p) is not None and "/tests/" not in p)
        yl = lines(crate, lambda p: "/rules/" in p and p.endswith(".yaml"))
        n = sum(t[k] for k in ("shared", "pattern", "family", "rust"))
        print(f"{lang:<15}{n:>5}{t['shared']:>7}{t['pattern']:>8}{t['family']:>7}{t['rust']:>5}{t['on']:>5}{rl:>11}{yl:>11}")
        for j, v in enumerate((n, t["shared"], t["pattern"], t["family"], t["rust"], t["on"], rl, yl)):
            tot[j] += v
    print(f"{'total (rows)':<15}" + "".join(f"{v:>{w}}" for v, w in zip(tot, (5, 7, 8, 7, 5, 5, 11, 11))))
    print(f"distinct ids: {len({r[0] for r in rows})}")


if __name__ == "__main__":
    main()
