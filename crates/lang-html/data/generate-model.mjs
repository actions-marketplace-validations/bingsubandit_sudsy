// Regenerates `model.txt` (the content model: see core-rules `content_model`) from the element
// metadata of html-validate (MIT):
//   node crates/lang-html/data/generate-model.mjs <dir with node_modules/html-validate> > crates/lang-html/data/model.txt
import { createRequire } from "node:module";
import { alternatives, excluded, groupBy, list, rows } from "../../../scripts/metadata-rows.mjs";
const { HtmlValidate } = createRequire(process.argv[2] + "/")("html-validate");
const pkg = createRequire(process.argv[2] + "/")("html-validate/package.json");
const config = await new HtmlValidate({ root: true }).getConfigFor("a.html");
const e = config.metaTable.elements;
const names = Object.keys(e).filter((n) => !n.includes(":")).sort();

const out = [];
out.push(`# Generated by generate-model.mjs from the element metadata of html-validate ${pkg.version} (MIT). Rows: see core-rules content_model.`);
out.push(`known ${names.join(",")}`);

const categories = { flow: "flow", phrasing: "phrasing", meta: "metadata", sectioning: "sectioning", heading: "heading", embedded: "embedded", interactive: "interactive", script: "scriptSupporting", form: "form", focusable: "focusable", submit: "submitButton" };
for (const [cat, key] of Object.entries(categories)) {
  const on = names.filter((n) => e[n][key] === true);
  if (on.length) out.push(`category ${cat} ${on.join(",")}`);
}
// Categories that the metadata computes from the element's attributes or place.
const dynamic = names.filter((n) => Object.keys(categories).some((c) => typeof e[n][categories[c]] === "function"));
const wanted = "area:flow:in:map area:phrasing:in:map link:flow:itemprop link:phrasing:itemprop meta:flow:itemprop meta:phrasing:itemprop a:interactive:href audio:interactive:controls video:interactive:controls img:interactive:usemap object:interactive:usemap input:interactive:type!=hidden a:focusable:href area:focusable:href audio:focusable:controls video:focusable:controls input:focusable:type!=hidden summary:focusable:in:details button:submit:!type button:submit:type=submit input:submit:type=submit|image";
const seen = new Set();
for (const w of wanted.split(" ")) {
  const [n, cat, ...cond] = w.split(":");
  if (typeof e[n][categories[cat]] !== "function") throw new Error(`${n} ${cat} is not dynamic any more`);
  seen.add(`${n}:${cat}`);
  out.push(`if ${cat} ${n} ${cond.join(":")}`);
}
for (const n of dynamic) for (const c of Object.keys(categories)) if (typeof e[n][categories[c]] === "function" && !seen.has(`${n}:${c}`)) throw new Error(`unhandled ${n} ${c}`);

// The rows: names grouped by the value of one metadata key.
const rowsOf = (kind, key, render) => {
  const on = names.filter((n) => e[n][key] !== undefined && e[n][key] !== false);
  out.push(...rows(kind, groupBy(on, (n) => render(e[n][key]))));
};
const strings = (v) => v.every((r) => typeof r === "string");
rowsOf("content", "permittedContent", (v) => (strings(v) ? list(v) : null));
rowsOf("exclude", "permittedDescendants", excluded);
rowsOf("order", "permittedOrder", alternatives);
rowsOf("required", "requiredContent", (v) => v.join(" "));
rowsOf("transparent", "transparent", (v) => (v === true ? "" : null));
const opened = names.filter((n) => e[n].implicitOpen);
out.push(...rows("open", groupBy(opened, (n) => e[n].implicitOpen.flatMap((o) => o.for.map((f) => `${f}:${o.open}`)).join(" "))));
rowsOf("closed", "implicitClosed", (v) => v.join(" "));
console.log(out.join("\n"));
