// Regenerates `baseline.txt` from the browser-support table bundled in @html-eslint/core (MIT; its data is the baseline data
// of web-features, Apache-2.0). Run by hand; the pin is `version` in docs/ai/parity/html-eslint.yaml:
//   node crates/lang-html/data/generate-baseline.mjs <dir with node_modules/@html-eslint/core> > crates/lang-html/data/baseline.txt
import { readFileSync } from "node:fs";
const dir = process.argv[2] + "/node_modules/@html-eslint/core";
const version = JSON.parse(readFileSync(dir + "/package.json", "utf8")).version;
const src = readFileSync(dir + "/dist/index.js", "utf8");
const at = src.indexOf("var globalAttributes = ");
const parts = [["", src.slice(src.indexOf("var elements = "), at)], ["@", src.slice(at, src.indexOf("// lib/utils/node.js"))]];
const rows = [];
for (const [mark, body] of parts) for (const m of body.matchAll(/\["([^"]+)", "(\d+):(\d*)"\]/g)) {
  let key = m[1];
  if (key.endsWith(".href.href_sms")) continue; // a prefix of the value (`sms:`), not a value
  key = key.replace(/^input\.type_/, "input.type.").replace(/^(td|th)\.rowspan\.rowspan_zero$/, "$1.rowspan.0");
  rows.push(`${mark}${key} ${m[2]} ${m[3]}`.trimEnd());
}
rows.sort();
console.log(`# Generated by generate-baseline.mjs from @html-eslint/core ${version} (MIT; data of web-features, Apache-2.0): "key status year"; the key is element, element.attribute or element.attribute.value, with @ before the attribute of a global one; status 10 widely, 5 newly, 0 not baseline; year of the baseline.`);
console.log(rows.join("\n"));
